"""Generate reference pages from the public exports without importing optional services."""

from __future__ import annotations

import argparse
import ast
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]

GROUPS = {
    "agents": (
        "Agents and runtimes",
        "Define agents, choose a runtime, attach tools and manage conversation turns.",
        {"agent"},
    ),
    "clients": (
        "Clients and transports",
        "The control-plane clients and embedded transport boundary. Native Desktop HTTP "
        "uses a separate client described in the Desktop reference.",
        {"client", "transport"},
    ),
    "desktop": (
        "Native Desktop API",
        "Direct, profile-bound HTTP bindings to a running Hermes Desktop server. "
        "Discover operations on the target server; mutations are not automatically retried.",
        {"desktop"},
    ),
    "integrations": (
        "Integrations and providers",
        "Profile-owned connectors, catalog discovery, installation and provider authentication. "
        "A catalog result does not imply installation consent or deployment support.",
        {
            "connectors", "plugin_catalog", "plugin_administration", "integration_mutations",
            "provider_auth", "provider_endpoints", "provider_oauth", "provider_administration",
            "channel_pairings", "channels_administration",
        },
    ),
    "administration": (
        "Administration",
        "Skills, context, profiles, local models and deployment administration. "
        "These helpers require their matching advertised backend extension.",
        {
            "administration", "auxiliary_administration", "local_models_administration",
            "memory_backends", "skill_administration", "skill_documents", "skill_reviews",
            "profile_imports", "profile_archives", "deployment", "session_context",
        },
    ),
    "workspace": (
        "Collaboration and workspace",
        "Bots, groups, schedules, files, Git, worktrees, media and application-owned "
        "extensions. Keep the owning profile and resource identity with each operation.",
        {
            "artifact_history", "audio", "browser_control", "client_wake", "command_actions",
            "command_center", "extensions", "file_mutations", "files", "git_mutations",
            "group_attachments", "group_dialogue", "group_membership", "kanban",
            "kanban_management", "live_audio", "room_peers", "room_policy",
            "schedule_mutations", "worktree_archives", "worktree_handoffs",
        },
    ),
    "errors": (
        "Errors",
        "HTTP error classes shared by the clients. Native transports can also raise "
        "timeout, connection and native protocol errors; see the reliability guide.",
        {"errors"},
    ),
}

DESKTOP_GROUPS = (
    "DesktopCron", "DesktopFiles", "DesktopGit", "DesktopSkills", "DesktopSessions",
)
RESOURCE_GROUPS = (
    "RootResource", "InstancesResource", "InstanceResource", "ProfilesResource",
    "ProfileResource", "SessionsResource", "SessionResource", "TurnsResource",
    "TurnResource", "BindingResource", "NativeResource",
)


def pages() -> dict[Path, str]:
    tree = ast.parse((ROOT / "src/edith_hermes/__init__.py").read_text(encoding="utf-8"))
    assignments = {
        node.targets[0].id: ast.literal_eval(node.value)
        for node in tree.body
        if isinstance(node, ast.Assign)
        and isinstance(node.targets[0], ast.Name)
        and node.targets[0].id in {"__all__", "__version__"}
    }
    imports = {
        name.asname or name.name: node.module
        for node in tree.body
        if isinstance(node, ast.ImportFrom)
        for name in node.names
    }
    grouped: dict[str, list[str]] = {slug: [] for slug in GROUPS}
    for export in assignments["__all__"]:
        module = imports[export]
        categories = [slug for slug, (_, _, modules) in GROUPS.items() if module in modules]
        if len(categories) != 1:
            raise ValueError(f"Give public export {export} in {module} exactly one reference category")
        grouped[categories[0]].append(export)

    result: dict[Path, str] = {}
    for slug, (title, introduction, _) in GROUPS.items():
        content = [
            "<!-- Generated by scripts/generate_api_reference.py; edit the source or generator. -->",
            f"# {title}", "", introduction, "",
            "[Choose your client](../guides/architecture.md) · "
            "[Reliability](../guides/reliability.md) · [All public exports](index.md)", "",
        ]
        content.extend(f"::: edith_hermes.{export}\n" for export in grouped[slug])
        if slug == "desktop":
            content.extend(f"::: edith_hermes.desktop.{name}\n" for name in DESKTOP_GROUPS)
            content.append("::: edith_hermes.desktop_plugin_catalog.DesktopPlugins\n")
        result[ROOT / f"docs/reference/{slug}.md"] = "\n".join(content)

    index = [
        "<!-- Generated by scripts/generate_api_reference.py; edit the source or generator. -->",
        "# API reference", "",
        f"Source version **{assignments['__version__']}** · "
        f"**{len(assignments['__all__'])} public exports**", "",
        "Signatures and available methods below are extracted from the SDK's actual Python "
        "source at documentation build time. No optional runtime or model is started.", "",
        "The SDK is asynchronous unless a class explicitly documents a synchronous facade. "
        "Use the correct service URL and keep the selected profile and native/control-plane "
        "session identities separate. [Architecture](../guides/architecture.md)", "",
        "## Public export index", "",
    ]
    for slug, (title, _, _) in GROUPS.items():
        index.extend([f"### [{title}]({slug}.md)", "", '<div class="sdk-api-index" markdown>', ""])
        index.extend(f"- [{name}]({slug}.md#edith_hermes.{name})" for name in grouped[slug])
        index.extend(["", "</div>", ""])
    index.extend([
        "", "## Generated resource handles", "",
        "[Resource handles](resources.md) cover instances, profiles, sessions, turns and "
        "the native gateway entry point. They are generated from the pinned contracts. "
        "Their presence in the SDK is not a runtime capability check.", "",
        "For individual generated request and response models, consult "
        "[the generated type modules](https://github.com/AnasMaar/edith-hermes-sdk/tree/main/src/edith_hermes/generated). "
        "Transport schemas and upstream source hashes live in "
        "[contracts](https://github.com/AnasMaar/edith-hermes-sdk/tree/main/contracts).", "",
    ])
    result[ROOT / "docs/reference/index.md"] = "\n".join(index)
    resources = [
        "<!-- Generated by scripts/generate_api_reference.py; edit the source or generator. -->",
        "# Resource handles", "",
        "These are generated resource entry points used by the convenience client. "
        "A resource handle stores identity; calls perform network work. "
        "The native gateway remains separate from native Desktop HTTP.", "",
        "The full generated resource module also contains individual native subsystems. "
        "Use the runtime's supported contract when calling those methods.", "",
    ]
    resources.extend(
        f"::: edith_hermes.generated.resources.{name}\n" for name in RESOURCE_GROUPS
    )
    result[ROOT / "docs/reference/resources.md"] = "\n".join(resources)
    return result


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="Fail if committed reference pages drift")
    args = parser.parse_args()
    stale = []
    for target, content in pages().items():
        if args.check:
            if not target.exists() or target.read_text(encoding="utf-8") != content:
                stale.append(str(target.relative_to(ROOT)))
        else:
            target.parent.mkdir(parents=True, exist_ok=True)
            target.write_text(content, encoding="utf-8", newline="\n")
    if stale:
        raise SystemExit("Regenerate API reference: " + ", ".join(stale))
